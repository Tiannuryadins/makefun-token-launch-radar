// Token Launch Radar — the value model (original work for token-radar-01).
//
// One sealed snapshot in, one ranked board out. The board covers every slug on
// the snapshot's watchlist (the floor, never the ceiling) and adds the
// strongest pre-token protocols below the floor, chosen by the model itself —
// by implied value, not by raw TVL.
//
// A protocol is pre-token when its record carries no token at all: no market
// cap, no CoinGecko id, no symbol. Protocols whose token already trades are
// kept apart and shown with the market's own values, never mixed into the
// ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   base      = tvl_usd x BASE_MULTIPLE
//   growth    = clamp(change_7d, -50, 150) per cent
//   growthF   = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity  = 0.7 + min(age_days, 730) / 730 x 0.3   (age unknown: 180 days)
//   breadth   = 1 + 0.03 x min(chains - 1, 4)
//   implied   = max(1, round(base x growthF x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row.
// The constants are stated in the dashboard and adjustable in its model panel.

/** One protocol entry of the sealed snapshot: exactly its ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_step: number;
  breadth_max_extra: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 730,
  unknown_age_days: 180,
  breadth_step: 0.03,
  breadth_max_extra: 4,
};

/** The model's version label, shown in the dashboard. */
export const MODEL_VERSION = 'radar-2';

/** How many pre-token protocols below the watchlist floor the board carries. */
export const EARLY_ROWS = 260;

/** How many live-token protocols the dashboard's market view carries. */
export const LIVE_ROWS = 24;

/** One farm step: the action, what it costs, and how long it takes. */
export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

/** One row of board.json. */
export interface BoardRow {
  rank: number;
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
  token_status: 'pre-token';
  age_days: number | null;
  on_watchlist: boolean;
  implied_value_usd: number;
  model: {
    base_multiple: number;
    growth_pct: number;
    growth_multiplier: number;
    maturity_multiplier: number;
    breadth_multiplier: number;
    age_days: number | null;
  };
  farm_steps: string[];
}

